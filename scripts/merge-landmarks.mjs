// Merge the per-landmark fragments in data/new/ into the files the app reads:
//   data/landmarks.json            (Russian source text + photos + credits)
//   src/locales/en.guimaraes.js    (English translations)
//   src/locales/pt.guimaraes.js    (Portuguese translations)
//
// Order follows data/landmarks.json, which also supplies lat/lon and the
// `model`/`osm` keys. Run after scripts/fetch-photos.mjs has filled the
// credits. Usage: node scripts/merge-landmarks.mjs [id ...]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NEW = join(ROOT, 'data', 'new');
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const args = process.argv.slice(2);
const dry = args.includes('--dry');
const only = args.filter((a) => !a.startsWith('-'));

const base = read(join(ROOT, 'data', 'landmarks.json'));
const order = base.map((l) => l.id);

const clean = (s) => (typeof s === 'string' ? s.replace(/assets\/img\/guimaraes\//g, 'assets/img/') : s);

const landmarks = [];
const en = {};
const pt = {};
const problems = [];

for (const id of order) {
  if (only.length && !only.includes(id)) continue;
  const cPath = join(NEW, `${id}.content.json`);
  const ePath = join(NEW, `${id}.en.json`);
  const pPath = join(NEW, `${id}.pt.json`);
  for (const p of [cPath, ePath, pPath]) {
    if (!existsSync(p)) problems.push(`${id}: missing ${p.replace(ROOT + '/', '')}`);
  }
  if (!existsSync(cPath)) continue;
  const c = read(cPath);
  const row = base.find((l) => l.id === id) || {};

  const entry = {
    id,
    name_pt: c.name_pt || row.name_pt,
    name_ru: c.name_ru || row.name_ru,
    category: c.category || row.category,
    lat: row.lat,
    lon: row.lon,
    year: c.year || '',
    short_ru: c.short_ru || '',
    long_ru: c.long_ru || '',
    model: row.model,
    image: clean(c.image),
    image_credit: c.image_credit || null,
    gallery: (c.gallery || []).map((g) => ({ src: clean(g.src), kind: g.kind, caption_ru: g.caption_ru, credit: g.credit })),
    videos: c.videos || [],
    panorama: c.panorama ?? null,
    history_ru: c.history_ru || '',
    facts_ru: c.facts_ru || [],
    sources: c.sources || [],
    tip_ru: c.tip_ru || '',
    osm: row.osm,
  };
  landmarks.push(entry);

  if (existsSync(ePath)) en[id] = read(ePath)[id];
  if (existsSync(pPath)) pt[id] = read(pPath)[id];

  if (!entry.image) problems.push(`${id}: no image`);
  else if (!existsSync(join(ROOT, entry.image))) problems.push(`${id}: image file missing ${entry.image}`);
  if (!entry.image_credit) problems.push(`${id}: no image_credit`);
  for (const g of entry.gallery) {
    if (!g.credit) problems.push(`${id}: gallery ${g.src} has no credit`);
    if (!existsSync(join(ROOT, g.src))) problems.push(`${id}: gallery file missing ${g.src}`);
  }
}

const dropProvisional = landmarks.length === order.length;

const header = (lang) =>
  `// ${lang} landmark texts for Guimarães. Generated by scripts/merge-landmarks.mjs\n` +
  `// from data/new/<id>.${lang === 'English' ? 'en' : 'pt'}.json. Russian is the source\n` +
  `// language and lives in data/landmarks.json.\n`;

const locale = (lang, obj) =>
  header(lang) + `export const landmarks = ${JSON.stringify(obj, null, 2)};\n\nexport const routes = {};\n`;

if (!dry) {
  writeFileSync(join(ROOT, 'data', 'landmarks.json'), JSON.stringify(landmarks, null, 2) + '\n');
  writeFileSync(join(ROOT, 'src', 'locales', 'en.guimaraes.js'), locale('English', en));
  writeFileSync(join(ROOT, 'src', 'locales', 'pt.guimaraes.js'), locale('Portuguese', pt));
}

console.log(`${dry ? '[dry] ' : ''}merged ${landmarks.length}/${order.length} landmarks -> data/landmarks.json`);
console.log(`en.guimaraes.js: ${Object.keys(en).length} entries; pt.guimaraes.js: ${Object.keys(pt).length}`);
if (!dropProvisional) console.warn(`note: some ids were skipped (${only.length ? only.join(', ') : 'none'})`);
if (problems.length) {
  console.warn(`\n${problems.length} problem(s):`);
  for (const p of problems) console.warn(`  - ${p}`);
  process.exitCode = 1;
} else {
  console.log('all landmarks have text, images and credits');
}
